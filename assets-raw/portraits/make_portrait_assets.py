"""Converts the generated personnel portraits into the small images the client ships.

Each portrait in manifest.json (<archetype>/<archetype>_NNN.png, 256x256, generated by
make_portraits.py) becomes assets/ui/portraits/<archetype>_NNN.jpg: greyscale, 128x128, JPEG.

- 128x128: the rows draw a portrait at 40 to 56 px, up to about 112 px on a high-DPI monitor;
  the client mipmaps it for the smaller sizes. 256x256 was only the smallest size the image model
  holds together at.
- Greyscale: the portraits are meant to be black-and-white period photographs; this removes the
  slight tint some came out with, so they all match.
- Saved as RGB, not single-channel: libGDX loads a one-channel image as an alpha texture, which
  would draw as a white smudge. With no colour in it, the extra channels cost almost nothing.

Usage:
    python make_portrait_assets.py            # convert every portrait, overwriting
    python make_portrait_assets.py --size 96  # try another size
"""
import argparse
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, 'manifest.json')
OUT = os.path.join(HERE, '..', '..', 'assets', 'ui', 'portraits')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--size', type=int, default=128)
    parser.add_argument('--quality', type=int, default=88)
    args = parser.parse_args()
    with open(MANIFEST, encoding='utf-8') as source:
        manifest = json.load(source)
    os.makedirs(OUT, exist_ok=True)
    total = 0
    for entry in manifest:
        source = os.path.join(HERE, entry['file'])
        if not os.path.exists(source):
            print('missing', entry['file'])
            continue
        image = Image.open(source).convert('L')
        image = image.resize((args.size, args.size), Image.LANCZOS).convert('RGB')
        target = os.path.join(OUT, os.path.splitext(os.path.basename(entry['file']))[0] + '.jpg')
        image.save(target, 'JPEG', quality=args.quality, optimize=True, progressive=False)
        total += os.path.getsize(target)
    print(f'{len(manifest)} portraits, {total / 1024:.0f} KB')
    return 0


if __name__ == '__main__':
    sys.exit(main())
