package de.mkoehler.launchwindow.content;

/**
 * The bodies programs are browsed by on Headquarters' solar-system screen (gap G9,
 * {@code ui-spec.md} &sect;4.6.2), in order from the Sun outwards, the Moon after Earth.
 *
 * @author Mario Koehler
 */
public enum CelestialBody {
    /** The Sun. */
    SUN,
    /** Mercury. */
    MERCURY,
    /** Venus. */
    VENUS,
    /** Earth, including Earth orbit. */
    EARTH,
    /** The Moon. */
    MOON,
    /** Mars. */
    MARS,
    /** Jupiter. */
    JUPITER,
    /** Saturn. */
    SATURN
}
